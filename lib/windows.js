/**
 * Windows integration: per-user login autostart (registry + generated launch
 * scripts) and a Windows-service installation plan for one declared service.
 *
 * Nothing here needs elevation except the service installation itself, which
 * reports that clearly and leaves a ready-to-run elevated script behind.
 */
import path from 'node:path'
import { run, ensureDir, expandEnv, writeFileAtomic, isElevated, nowIso } from './util.js'
import { resolveCaddyExe } from './caddy.js'

/** Registry value that starts the whole stack at user login. */
export const RUN_VALUE = 'DSHServiceManage'
const RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run'

/**
 * Build (and write) the login-autostart scripts for the current registry.
 * @param {import('./store.js').Store} store - registry store.
 * @returns {Promise<{startAll: string, vbs: string, services: string[]}>} generated paths.
 */
export async function writeAutostartScripts(store) {
  const dir = store.dirs.autostart
  const servicesDir = path.join(dir, 'services')
  await ensureDir(servicesDir)
  const services = []
  const lines = [
    '@echo off',
    'rem Generated by dsh-service-manage — starts the proxy and services marked "boot".',
    'setlocal',
    `cd /d "${store.dataDir}"`,
  ]
  // The login launcher owns the proxy: it starts Caddy even though "start Caddy
  // with DSH" is off, because at login nothing else has started it yet.
  lines.push(`start "" /b "${resolveCaddyExe(store.settings)}" run --config "${store.caddyfile}"`)
  for (const service of store.services) {
    if (service.autoStart !== 'boot') continue
    if (service.manage === 'external') continue
    const file = path.join(servicesDir, `${service.id}.cmd`)
    const body = [
      '@echo off',
      `rem ${service.name}`,
      `cd /d "${path.resolve(expandEnv(service.cwd || store.dataDir))}"`,
      ...Object.entries(service.env ?? {}).map(([key, value]) => `set "${key}=${value}"`),
      expandEnv(service.command),
      '',
    ].join('\r\n')
    await writeFileAtomic(file, body)
    services.push(file)
    lines.push(`start "" /b "${file}"`)
  }
  lines.push('endlocal', '')
  const startAll = path.join(dir, 'start-all.cmd')
  await writeFileAtomic(startAll, `${lines.join('\r\n')}\r\n`)

  const vbs = path.join(dir, 'start-all.vbs')
  await writeFileAtomic(
    vbs,
    [
      "' Generated by dsh-service-manage",
      'Set sh = CreateObject("WScript.Shell")',
      `sh.Run """${startAll}""", 0, False`,
      '',
    ].join('\r\n'),
  )
  return { startAll, vbs, services }
}

/**
 * Report whether the login autostart value exists.
 * @returns {Promise<boolean>} true when the registry value is present.
 */
export async function isAutostartEnabled() {
  const result = await run('reg', ['query', RUN_KEY, '/v', RUN_VALUE], { timeout: 8000 })
  return result.code === 0
}

/**
 * Enable or disable login autostart, regenerating the launch scripts first.
 * @param {import('./store.js').Store} store - registry store.
 * @param {boolean} enabled - desired state.
 * @returns {Promise<{ok: boolean, enabled: boolean, output: string, scripts?: any}>} the result.
 */
export async function setAutostart(store, enabled) {
  const scripts = await writeAutostartScripts(store)
  if (!enabled) {
    const result = await run('reg', ['delete', RUN_KEY, '/v', RUN_VALUE, '/f'], { timeout: 8000 })
    const gone = !(await isAutostartEnabled())
    return { ok: gone, enabled: gone, output: `${result.stdout}${result.stderr}`.trim() }
  }
  const value = `wscript.exe "${scripts.vbs}"`
  const result = await run(
    'reg',
    ['add', RUN_KEY, '/v', RUN_VALUE, '/t', 'REG_SZ', '/d', value, '/f'],
    { timeout: 8000 },
  )
  const now = await isAutostartEnabled()
  return { ok: now, enabled: now, output: `${result.stdout}${result.stderr}`.trim(), scripts }
}

/**
 * Compose everything an elevated install needs for one service.
 * @param {import('./store.js').Store} store - registry store.
 * @param {Record<string, any>} service - stored service.
 * @returns {Promise<Record<string, any>>} the installation plan.
 */
export async function windowsServicePlan(store, service) {
  const folder = path.join(store.dirs.windowsService, service.id)
  await ensureDir(folder)
  const name = `DSH-ServiceManage-${service.id}`
  const launcher = path.join(folder, 'launcher.cmd')
  const cwd = path.resolve(expandEnv(service.cwd || store.dataDir))
  await writeFileAtomic(
    launcher,
    [
      '@echo off',
      `rem ${service.name} — launched by the Windows service ${name}`,
      `cd /d "${cwd}"`,
      ...Object.entries(service.env ?? {}).map(([key, value]) => `set "${key}=${value}"`),
      expandEnv(service.command),
      '',
    ].join('\r\n'),
  )

  const safeDisplay = service.name.replace(/"/g, "'")
  const install = path.join(folder, 'install.ps1')
  await writeFileAtomic(
    install,
    [
      '# Generated by dsh-service-manage. Run in an elevated PowerShell.',
      `$ErrorActionPreference = 'Stop'`,
      `$name = ${jsonString(name)}`,
      `$bin  = ${jsonString(`cmd.exe /d /s /c ""${launcher}""`)}`,
      `if (Get-Service -Name $name -ErrorAction SilentlyContinue) { throw "service $name already exists" }`,
      `New-Service -Name $name -BinaryPathName $bin -DisplayName ${jsonString(`DSH service: ${safeDisplay}`)} ` +
        `-Description ${jsonString(service.description || service.name)} -StartupType Automatic | Out-Null`,
      `Start-Service -Name $name`,
      `Get-Service -Name $name | Format-List Name,Status,StartType`,
      '',
    ].join('\r\n'),
  )

  const uninstall = path.join(folder, 'uninstall.ps1')
  await writeFileAtomic(
    uninstall,
    [
      '# Generated by dsh-service-manage. Run in an elevated PowerShell.',
      `$ErrorActionPreference = 'Stop'`,
      `$name = ${jsonString(name)}`,
      `Stop-Service -Name $name -Force -ErrorAction SilentlyContinue`,
      `sc.exe delete $name`,
      '',
    ].join('\r\n'),
  )

  return {
    service: service.id,
    name,
    launcher,
    install,
    uninstall,
    binPath: `cmd.exe /d /s /c ""${launcher}""`,
    command: `powershell -NoProfile -ExecutionPolicy Bypass -File "${install}"`,
    generatedAt: nowIso(),
  }
}

/**
 * Try to register the service. Without elevation this returns the plan and the
 * exact elevated command instead of failing vaguely.
 * @param {import('./store.js').Store} store - registry store.
 * @param {Record<string, any>} service - stored service.
 * @returns {Promise<Record<string, any>>} registration outcome plus the plan.
 */
export async function registerWindowsService(store, service) {
  const plan = await windowsServicePlan(store, service)
  const elevated = await isElevated()
  if (!elevated) {
    return {
      ok: false,
      requiresElevation: true,
      output: 'Registering a Windows service needs an elevated shell. The install script is ready.',
      plan,
    }
  }
  const result = await run(
    'powershell',
    ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', plan.install],
    { timeout: 60000 },
  )
  return {
    ok: result.code === 0,
    requiresElevation: false,
    output: `${result.stdout}${result.stderr}`.trim(),
    plan,
  }
}

/**
 * Remove a previously registered Windows service.
 * @param {import('./store.js').Store} store - registry store.
 * @param {Record<string, any>} service - stored service.
 * @returns {Promise<Record<string, any>>} the outcome.
 */
export async function unregisterWindowsService(store, service) {
  const plan = await windowsServicePlan(store, service)
  const elevated = await isElevated()
  if (!elevated) {
    return {
      ok: false,
      requiresElevation: true,
      output: 'Removing a Windows service needs an elevated shell. The uninstall script is ready.',
      plan,
    }
  }
  const result = await run(
    'powershell',
    ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', plan.uninstall],
    { timeout: 60000 },
  )
  return { ok: result.code === 0, requiresElevation: false, output: `${result.stdout}${result.stderr}`.trim(), plan }
}

/**
 * Quote a value as a PowerShell single-quoted string.
 * @param {string} value - raw text.
 * @returns {string} the literal.
 */
function jsonString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}
