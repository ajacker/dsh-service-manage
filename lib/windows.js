/**
 * Windows integration: per-user login autostart (registry + generated launch
 * scripts) and Windows services for the proxy or a managed process.
 *
 * Two autostart mechanisms are supported for each entry and they are mutually
 * exclusive in the generated script: an installed Windows service wins, and the
 * login launcher only starts what no service covers.
 *
 * Every PowerShell file is written with a UTF-8 BOM: Windows PowerShell reads a
 * BOM-less .ps1 as ANSI, which mangled the Chinese description and produced a
 * "string is missing the terminator" parse error on install.
 */
import path from 'node:path'
import { existsSync } from 'node:fs'
import { stat } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { run, ensureDir, expandEnv, isElevated, nowIso, writeFileAtomic } from './util.js'
import { resolveCaddyExe } from './caddy.js'

/** Registry value that starts the whole stack at user login. */
export const RUN_VALUE = 'DSHServiceManage'
const RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run'
const BOM = '\uFEFF'

/** Windows service name for the reverse proxy. */
export const CADDY_SERVICE = 'DSH-ServiceManage-caddy'

/**
 * Windows service name for one declared service.
 * @param {string} id - service id.
 * @returns {string} the SCM name.
 */
export function serviceName(id) {
  return `DSH-ServiceManage-${id}`
}

/** @type {Map<string, {at: number, value: {exists: boolean, status: string}}>} */
const stateCache = new Map()

/**
 * Read whether a Windows service exists and its state, cached for a few seconds
 * so a panel poll does not spawn one `sc` per row.
 * @param {string} name - SCM service name.
 * @param {boolean} [force] - ignore the cache.
 * @returns {Promise<{exists: boolean, status: string}>} the observation.
 */
export async function serviceState(name, force = false) {
  const cached = stateCache.get(name)
  if (!force && cached && Date.now() - cached.at < 3000) return cached.value
  const result = await run('sc', ['query', name], { timeout: 6000 })
  let value = { exists: false, status: 'missing' }
  if (result.code === 0) {
    const match = /STATE\s*:\s*\d+\s+([A-Z_]+)/i.exec(result.stdout)
    value = { exists: true, status: (match?.[1] ?? 'unknown').toLowerCase() }
  }
  stateCache.set(name, { at: Date.now(), value })
  return value
}

/**
 * Start or stop an installed Windows service through the SCM.
 *
 * The SCM is the only thing that may touch a service process: killing whoever
 * listens on the port instead leaves the service in a stopped state and makes
 * the next plugin start race it for the port.
 *
 * @param {string} name - SCM service name.
 * @param {'start' | 'stop'} action - control to send.
 * @returns {Promise<{ok: boolean, output: string}>} the SCM answer.
 */
export async function controlService(name, action) {
  const result = await run('sc', [action, name], { timeout: 30000 })
  const output = `${result.stdout}${result.stderr}`.trim()
  stateCache.delete(name)
  return { ok: result.code === 0, output }
}

/**
 * Poll the SCM until a service reaches one of the wanted states.
 * @param {string} name - SCM service name.
 * @param {string[]} wanted - accepted states, e.g. `['running']`.
 * @param {number} [timeoutMs] - how long to wait.
 * @returns {Promise<{ok: boolean, status: string}>} the last observation.
 */
export async function waitServiceState(name, wanted, timeoutMs = 25000) {
  const deadline = Date.now() + timeoutMs
  let state = await serviceState(name, true)
  for (;;) {
    if (!state.exists) return { ok: false, status: 'missing' }
    if (wanted.includes(state.status)) return { ok: true, status: state.status }
    if (Date.now() >= deadline) return { ok: false, status: state.status }
    await new Promise(resolve => setTimeout(resolve, 400))
    state = await serviceState(name, true)
  }
}

/**
 * Write one PowerShell file that Windows PowerShell 5.1 and pwsh both parse.
 * @param {string} file - absolute path.
 * @param {string} text - body without a BOM.
 * @returns {Promise<void>} resolves after the write.
 */
async function writePs1(file, text) {
  await writeFileAtomic(file, `${BOM}${text}`)
}

/**
 * Build (and write) the login-autostart scripts for the current registry.
 * Entries covered by a Windows service are left out so login never starts a
 * second copy of something the SCM already owns.
 * @param {import('./store.js').Store} store - registry store.
 * @returns {Promise<{startAll: string, vbs: string, services: string[], caddy: boolean}>} generated paths.
 */
export async function writeAutostartScripts(store) {
  const dir = store.dirs.autostart
  const servicesDir = path.join(dir, 'services')
  await ensureDir(servicesDir)
  const services = []
  const lines = [
    '@echo off',
    'rem Generated by dsh-service-manage — starts what no Windows service already covers.',
    'setlocal',
    `cd /d "${store.dataDir}"`,
  ]

  let caddy = false
  const caddySvc = await serviceState(CADDY_SERVICE)
  if (!caddySvc.exists && store.settings.caddyBootMode !== 'none') {
    lines.push(`start "" /b "${resolveCaddyExe(store.settings)}" run --config "${store.caddyfile}"`)
    caddy = true
  }
  for (const service of store.services) {
    if (service.autoStart !== 'boot') continue
    if (service.manage === 'external') continue
    const state = await serviceState(serviceName(service.id))
    if (state.exists) continue
    const file = path.join(servicesDir, `${service.id}.cmd`)
    const body = [
      '@echo off',
      `rem ${service.name}`,
      `cd /d "${path.resolve(expandEnv(service.cwd || store.dataDir))}"`,
      ...Object.entries(service.env ?? {}).map(([key, value]) => `set "${key}=${value}"`),
      expandEnv(service.command),
      '',
    ].join('\r\n')
    await writeFileAtomic(file, body)
    services.push(file)
    lines.push(`start "" /b "${file}"`)
  }
  lines.push('endlocal', '')
  const startAll = path.join(dir, 'start-all.cmd')
  await writeFileAtomic(startAll, `${lines.join('\r\n')}\r\n`)

  const vbs = path.join(dir, 'start-all.vbs')
  await writeFileAtomic(
    vbs,
    [
      "' Generated by dsh-service-manage",
      'Set sh = CreateObject("WScript.Shell")',
      `sh.Run """${startAll}""", 0, False`,
      '',
    ].join('\r\n'),
  )
  return { startAll, vbs, services, caddy }
}

/**
 * Report whether the login autostart value exists.
 * @returns {Promise<boolean>} true when the registry value is present.
 */
export async function isAutostartEnabled() {
  const result = await run('reg', ['query', RUN_KEY, '/v', RUN_VALUE], { timeout: 8000 })
  return result.code === 0
}

/**
 * Enable or disable login autostart, regenerating the launch scripts first.
 * @param {import('./store.js').Store} store - registry store.
 * @param {boolean} enabled - desired state.
 * @returns {Promise<{ok: boolean, enabled: boolean, output: string, scripts?: any}>} the result.
 */
export async function setAutostart(store, enabled) {
  const scripts = await writeAutostartScripts(store)
  if (!enabled) {
    const result = await run('reg', ['delete', RUN_KEY, '/v', RUN_VALUE, '/f'], { timeout: 8000 })
    const gone = !(await isAutostartEnabled())
    return { ok: gone, enabled: gone, output: `${result.stdout}${result.stderr}`.trim() }
  }
  const value = `wscript.exe "${scripts.vbs}"`
  const result = await run(
    'reg',
    ['add', RUN_KEY, '/v', RUN_VALUE, '/t', 'REG_SZ', '/d', value, '/f'],
    { timeout: 8000 },
  )
  const now = await isAutostartEnabled()
  return { ok: now, enabled: now, output: `${result.stdout}${result.stderr}`.trim(), scripts }
}

/** Source of the bundled service host, compiled on first use. */
const HOST_SOURCE = fileURLToPath(new URL('../assets/ServiceHost.cs', import.meta.url))

/**
 * Build (or reuse) the bundled service host.
 *
 * A service binary must implement the SCM handshake, so `cmd.exe /c x.cmd`
 * fails with error 1053. This host does the handshake, runs the launcher and
 * kills the tree on stop. It is compiled here with the csc.exe that ships with
 * the .NET Framework, so the plugin carries no third-party executable.
 * @param {import('./store.js').Store} store - registry store.
 * @returns {Promise<string>} absolute path of ServiceHost.exe.
 */
export async function ensureServiceHost(store) {
  await ensureDir(store.dirs.windowsService)
  const exe = path.join(store.dirs.windowsService, 'ServiceHost.exe')
  const sourceStat = await stat(HOST_SOURCE)
  const exeStat = await stat(exe).catch(() => null)
  if (exeStat && exeStat.mtimeMs >= sourceStat.mtimeMs) return exe

  const windir = process.env.WINDIR ?? 'C:\\Windows'
  const candidates = [
    path.join(windir, 'Microsoft.NET', 'Framework64', 'v4.0.30319', 'csc.exe'),
    path.join(windir, 'Microsoft.NET', 'Framework', 'v4.0.30319', 'csc.exe'),
  ]
  const csc = candidates.find(candidate => existsSync(candidate))
  if (!csc) {
    throw new Error('no C# compiler found (csc.exe); the .NET Framework 4 that ships with Windows is required to build the service host')
  }
  const result = await run(
    csc,
    ['/nologo', '/target:exe', `/out:${exe}`, '/r:System.dll', '/r:System.ServiceProcess.dll', HOST_SOURCE],
    { timeout: 120000 },
  )
  if (result.code !== 0 || !existsSync(exe)) {
    throw new Error(`building ServiceHost.exe failed: ${`${result.stdout}${result.stderr}`.trim()}`)
  }
  return exe
}

/**
 * Compose everything an elevated install needs for one SCM entry.
 * @param {{store: import('./store.js').Store, id: string, name: string, display: string, description: string, cwd: string, command: string, env?: Record<string,string>}} input - plan inputs.
 * @returns {Promise<Record<string, any>>} the installation plan.
 */
export async function buildServicePlan(input) {
  const folder = path.join(input.store.dirs.windowsService, input.id)
  await ensureDir(folder)
  const name = serviceName(input.id)
  const launcher = path.join(folder, 'launcher.cmd')
  await writeFileAtomic(
    launcher,
    [
      '@echo off',
      `rem ${input.name} — launched by the Windows service ${name}`,
      `cd /d "${path.resolve(expandEnv(input.cwd || input.store.dataDir))}"`,
      ...Object.entries(input.env ?? {}).map(([key, value]) => `set "${key}=${value}"`),
      expandEnv(input.command),
      '',
    ].join('\r\n'),
  )

  const display = `DSH service: ${input.display || input.name}`.replace(/"/g, "'")
  const host = await ensureServiceHost(input.store)
  const binPath = `"${host}" --name ${name} --launcher "${launcher}"`
  const install = path.join(folder, 'install.ps1')
  await writePs1(
    install,
    [
      '# Generated by dsh-service-manage. Run in an elevated PowerShell.',
      "$ErrorActionPreference = 'Stop'",
      `$name = ${psiString(name)}`,
      `$bin  = ${psiString(binPath)}`,
      `if (Get-Service -Name $name -ErrorAction SilentlyContinue) { throw "service $name already exists" }`,
      `New-Service -Name $name -BinaryPathName $bin -DisplayName ${psiString(display)} -StartupType Automatic | Out-Null`,
      `sc.exe description $name ${psiString(String(input.description || input.name))} | Out-Null`,
      `Start-Service -Name $name`,
      'Get-Service -Name $name | Format-List Name,Status,StartType',
      '',
    ].join('\r\n'),
  )

  const uninstall = path.join(folder, 'uninstall.ps1')
  await writePs1(
    uninstall,
    [
      '# Generated by dsh-service-manage. Run in an elevated PowerShell.',
      "$ErrorActionPreference = 'Stop'",
      `$name = ${psiString(name)}`,
      'Stop-Service -Name $name -Force -ErrorAction SilentlyContinue',
      'sc.exe delete $name',
      'Get-Service -Name $name -ErrorAction SilentlyContinue',
      '',
    ].join('\r\n'),
  )

  return {
    id: input.id,
    name,
    launcher,
    install,
    uninstall,
    binPath,
    command: `powershell -NoProfile -ExecutionPolicy Bypass -File "${install}"`,
    generatedAt: nowIso(),
  }
}

/**
 * Plan for one declared service.
 * @param {import('./store.js').Store} store - registry store.
 * @param {Record<string, any>} service - stored service.
 * @returns {Promise<Record<string, any>>} the plan.
 */
export async function windowsServicePlan(store, service) {
  return buildServicePlan({
    store,
    id: service.id,
    name: service.name,
    display: service.name,
    description: service.description || service.name,
    cwd: service.cwd,
    command: service.command,
    env: service.env,
  })
}

/**
 * Plan for the reverse proxy itself.
 * @param {import('./store.js').Store} store - registry store.
 * @returns {Promise<Record<string, any>>} the plan.
 */
export async function caddyServicePlan(store) {
  return buildServicePlan({
    store,
    id: 'caddy',
    name: 'Caddy reverse proxy',
    display: 'Caddy 反向代理',
    description: `Caddy reverse proxy for ${store.caddyfile}`,
    cwd: store.dataDir,
    command: `"${resolveCaddyExe(store.settings)}" run --config "${store.caddyfile}"`,
  })
}

/**
 * Run one generated script through an elevated PowerShell. `Start-Process
 * -Verb RunAs` raises the UAC prompt, so a panel click can register a service
 * without the user opening a terminal themselves.
 * @param {string} file - PowerShell script to execute.
 * @returns {Promise<{ok: boolean, output: string}>} the elevated run outcome.
 */
async function runElevatedScript(file) {
  const quoted = String(file).replace(/'/g, "''")
  const command = `$p = Start-Process -FilePath powershell.exe -Verb RunAs -Wait -PassThru `
    + `-ArgumentList '-NoProfile','-ExecutionPolicy','Bypass','-File','${quoted}'; exit $p.ExitCode`
  const result = await run(
    'powershell',
    ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', command],
    { timeout: 90000 },
  )
  return { ok: result.code === 0, output: `${result.stdout}${result.stderr}`.trim() }
}

/**
 * Install one service from its plan, or return the elevated command when this
 * process cannot register services.
 * @param {Record<string, any>} plan - plan from buildServicePlan.
 * @param {string} label - human-readable subject for the message.
 * @returns {Promise<Record<string, any>>} the outcome.
 */
export async function installService(plan, label) {
  if (!(await isElevated())) {
    const result = await runElevatedScript(plan.install)
    stateCache.delete(plan.name)
    return {
      ...result,
      requiresElevation: false,
      elevatedViaUac: true,
      output: result.ok
        ? `${label}: Windows service installed after the elevation prompt`
        : `${label}: elevation was cancelled or failed. Run this as administrator:\n${plan.command}`,
      plan,
    }
  }
  const result = await run('powershell', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', plan.install], {
    timeout: 90000,
  })
  stateCache.delete(plan.name)
  return { ok: result.code === 0, requiresElevation: false, output: `${result.stdout}${result.stderr}`.trim(), plan }
}

/**
 * Remove one service from its plan.
 * @param {Record<string, any>} plan - plan from buildServicePlan.
 * @param {string} label - human-readable subject for the message.
 * @returns {Promise<Record<string, any>>} the outcome.
 */
export async function removeService(plan, label) {
  if (!(await isElevated())) {
    const result = await runElevatedScript(plan.uninstall)
    stateCache.delete(plan.name)
    return {
      ...result,
      requiresElevation: false,
      elevatedViaUac: true,
      output: result.ok
        ? `${label}: Windows service removed after the elevation prompt`
        : `${label}: elevation was cancelled or failed. Run this as administrator:\n${plan.command.replace(/install\.ps1/, 'uninstall.ps1')}`,
      plan,
    }
  }
  const result = await run('powershell', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', plan.uninstall], {
    timeout: 90000,
  })
  stateCache.delete(plan.name)
  return { ok: result.code === 0, requiresElevation: false, output: `${result.stdout}${result.stderr}`.trim(), plan }
}

/**
 * Register one declared service as a Windows service.
 * @param {import('./store.js').Store} store - registry store.
 * @param {Record<string, any>} service - stored service.
 * @returns {Promise<Record<string, any>>} registration outcome plus the plan.
 */
export async function registerWindowsService(store, service) {
  return installService(await windowsServicePlan(store, service), service.name)
}

/**
 * Remove a previously registered Windows service.
 * @param {import('./store.js').Store} store - registry store.
 * @param {Record<string, any>} service - stored service.
 * @returns {Promise<Record<string, any>>} the outcome.
 */
export async function unregisterWindowsService(store, service) {
  return removeService(await windowsServicePlan(store, service), service.name)
}

/**
 * Quote a value as a PowerShell single-quoted string.
 * @param {string} value - raw text.
 * @returns {string} the literal.
 */
function psiString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}
