/**
 * Caddy control plane: render the managed Caddyfile from routes, validate it,
 * reload or restart the proxy, and report what is actually running.
 *
 * Rendering is deliberately boring: one file per concern. The generated route
 * block lives in `routes/_managed.caddy`, hand-written snippets live in
 * `custom/*.caddy`, and the main Caddyfile only wires imports together plus the
 * 404 fallback. In `manual` mode the main Caddyfile is owned by the user and is
 * never rewritten.
 */
import path from 'node:path'
import { existsSync } from 'node:fs'
import { readdir, readFile, unlink } from 'node:fs/promises'
import { attachProcessLog, caddyQuote, ensureDir, isPortListening, nowIso, run, spawnCaptured, writeFileAtomic } from './util.js'

/** Header comment placed at the top of every generated file. */
const GENERATED_BANNER = [
  '# Generated by dsh-service-manage — edits are replaced in managed mode.',
  '# Switch the panel to manual mode to own this file by hand.',
]

/** Default CORS header set for API-style routes. */
const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'Authorization, Content-Type, X-Api-Key',
  'Access-Control-Allow-Methods': 'POST, GET, OPTIONS',
}

/**
 * Resolve the caddy executable from settings without constructing a controller:
 * an explicit absolute path wins, then the common install locations, then the
 * configured name for PATH lookup.
 * @param {Record<string, any>} settings - store settings.
 * @returns {string} an executable name or absolute path.
 */
export function resolveCaddyExe(settings = {}) {
  const configured = String(settings.caddyExe ?? '').trim() || 'caddy'
  if (path.isAbsolute(configured) && existsSync(configured)) return configured
  const candidates = [
    path.join(process.env.LOCALAPPDATA ?? '', 'Microsoft', 'WinGet', 'Links', 'caddy.exe'),
    path.join(process.env.ProgramFiles ?? 'C:\\Program Files', 'Caddy', 'caddy.exe'),
    path.join(process.env.ProgramData ?? 'C:\\ProgramData', 'chocolatey', 'bin', 'caddy.exe'),
  ]
  for (const candidate of candidates) {
    if (candidate && existsSync(candidate)) return candidate
  }
  return configured
}

/** Controls the Caddy process and the generated configuration. */
export class Caddy {
  /**
   * @param {import('./store.js').Store} store - registry store.
   */
  constructor(store) {
    this.store = store
    this.child = undefined
    this.childLog = undefined
    this.resolvedExe = undefined
  }

  /** @returns {string} absolute path of the main Caddyfile. */
  get configPath() {
    return this.store.caddyfile
  }

  /** @returns {string} absolute path of the generated route file. */
  get managedRoutePath() {
    return path.join(this.store.dirs.routes, '_managed.caddy')
  }

  /**
   * Resolve the caddy executable once: explicit path, PATH, then the winget link.
   * @returns {string} an executable name or absolute path.
   */
  exe() {
    if (!this.resolvedExe) this.resolvedExe = resolveCaddyExe(this.store.settings)
    return this.resolvedExe
  }

  /**
   * Render the managed configuration when the panel owns the Caddyfile.
   * @param {{force?: boolean}} [options] - `force` renders even in manual mode (used by "switch back").
   * @returns {Promise<{mode: string, caddyfile: string, routeFile: string, routes: number, snippets: number}>} what was written.
   */
  async render(options = {}) {
    const mode = this.store.state.caddy.mode
    if (mode === 'manual' && options.force !== true) {
      return {
        mode,
        caddyfile: this.configPath,
        routeFile: this.managedRoutePath,
        routes: 0,
        snippets: 0,
      }
    }
    await ensureDir(path.dirname(this.configPath))
    await ensureDir(this.store.dirs.routes)
    await ensureDir(this.store.dirs.custom)

    const main = this.buildMain()
    await writeFileAtomic(this.configPath, main)

    const routes = this.store.routes.filter(route => route.enabled)
    const routeText = [
      ...GENERATED_BANNER,
      `# ${routes.length} route(s) · rendered ${nowIso()}`,
      '',
      ...routes.map(route => this.buildRoute(route)),
    ].join('\n')
    await writeFileAtomic(this.managedRoutePath, routeText)

    await this.syncSnippets()
    return {
      mode: this.store.state.caddy.mode,
      caddyfile: this.configPath,
      routeFile: this.managedRoutePath,
      routes: routes.length,
      snippets: this.store.snippets.length,
    }
  }

  /**
   * Write one file per hand-written snippet and remove files for deleted ones.
   * @returns {Promise<void>} resolves after the directory matches the registry.
   */
  async syncSnippets() {
    await ensureDir(this.store.dirs.custom)
    const wanted = new Set()
    for (const snippet of this.store.snippets) {
      const file = path.join(this.store.dirs.custom, `${snippet.id}.caddy`)
      wanted.add(path.basename(file))
      const body = [
        `# custom snippet: ${snippet.name} (${snippet.id})`,
        snippet.content.trim(),
        '',
      ].join('\n')
      await writeFileAtomic(file, body)
    }
    let existing = []
    try {
      existing = await readdir(this.store.dirs.custom)
    } catch {
      existing = []
    }
    for (const name of existing) {
      if (!name.endsWith('.caddy')) continue
      if (wanted.has(name) || name === '_empty.caddy') continue
      await unlink(path.join(this.store.dirs.custom, name)).catch(() => {})
    }
    if (wanted.size === 0) {
      await writeFileAtomic(path.join(this.store.dirs.custom, '_empty.caddy'), '# no custom snippets\n')
    }
  }

  /**
   * Compose the main Caddyfile.
   * @returns {string} the file body.
   */
  buildMain() {
    const settings = this.store.settings
    const admin = String(settings.adminEndpoint ?? '127.0.0.1:2019').trim()
    const listen = String(settings.proxyListen ?? ':8080').trim()
    const global = []
    if (admin) global.push(`\tadmin ${admin}`)
    global.push('\tauto_https off')
    if (settings.trustProxyHeaders !== false) {
      global.push('\tservers {', '\t\ttrusted_proxies static private_ranges 127.0.0.1 ::1', '\t}')
    }
    const lines = [
      '# dsh-service-manage · managed mode',
      '# Routes: routes/_managed.caddy (panel) · Snippets: custom/*.caddy (hand-written)',
      '# To take over by hand, switch the panel to manual mode.',
      '',
      '{',
      ...global,
      '}',
      '',
      `${listen} {`,
      '\timport routes/_managed.caddy',
      '\timport custom/*.caddy',
      '',
      '\thandle {',
      '\t\trespond "Not Found" 404',
      '\t}',
      '}',
      '',
    ]
    return lines.join('\n')
  }

  /**
   * Render one structured route as a Caddyfile fragment.
   * @param {Record<string, any>} route - normalized route.
   * @returns {string} the fragment.
   */
  buildRoute(route) {
    if (route.raw && route.raw.trim().length > 0) {
      return [`# ${route.id} · ${route.name} (raw)`, route.raw.trim(), ''].join('\n')
    }
    const safe = route.id.replace(/[^A-Za-z0-9_]/g, '_')
    const matcher = `@svc_${safe}`
    const conditions = []
    if (route.match.host) conditions.push(`\thost ${caddyQuote(route.match.host)}`)
    const pathMatcher = route.match.exact
      ? route.match.path
      : route.match.path.endsWith('*')
        ? route.match.path
        : `${route.match.path}*`
    conditions.push(`\tpath ${caddyQuote(pathMatcher)}`)

    const out = [`# ${route.id} · ${route.name}`, `${matcher} {`, ...conditions, '}']
    const preflight = `${matcher}_opt`
    if (route.cors) out.push(`${preflight} method OPTIONS`)
    out.push(`handle ${matcher} {`)
    if (route.stripPrefix) {
      out.push(`\turi strip_prefix ${caddyQuote(route.match.path.replace(/\*+$/, '') || '/')}`)
    }

    if (route.auth.type === 'basic' && route.auth.hash) {
      out.push('\tbasic_auth {', `\t\t${caddyQuote(route.auth.user || 'user')} ${route.auth.hash}`, '\t}')
    }
    if (route.cors) {
      out.push('\theader {')
      for (const [key, value] of Object.entries(CORS_HEADERS)) {
        out.push(`\t\t${key} ${caddyQuote(value)}`)
      }
      out.push('\t}')
      out.push(`\trespond ${preflight} 204`)
    }
    if (route.kind === 'proxy') {
      const upstream = String(route.upstream).trim()
      const headerUp = Object.entries(route.headerUp ?? {}).filter(([key]) => key.toLowerCase() !== '')
      if (headerUp.length > 0) {
        out.push(`\treverse_proxy ${upstream} {`)
        for (const [key, value] of headerUp) out.push(`\t\theader_up ${key} ${caddyQuote(value)}`)
        out.push('\t}')
      } else {
        out.push(`\treverse_proxy ${upstream}`)
      }
    } else if (route.kind === 'redirect') {
      out.push(`\tredir * ${caddyQuote(route.redirect.to || '/')} ${route.redirect.code || 308}`)
    } else {
      out.push(`\troot * ${caddyQuote(route.static.root || '.')}`)
      if (route.static.rewrite) out.push(`\trewrite * ${caddyQuote(route.static.rewrite)}`)
      out.push('\tfile_server')
    }
    out.push('}', '')
    return out.join('\n')
  }

  /**
   * Validate the current Caddyfile without touching the running proxy.
   * @returns {Promise<{ok: boolean, output: string, config: string}>} the validation result.
   */
  async validate() {
    const file = this.configPath
    if (!existsSync(file)) {
      return { ok: false, output: `Caddyfile not found: ${file}`, config: file }
    }
    const result = await run(this.exe(), ['validate', '--config', file, '--adapter', 'caddyfile'], {
      timeout: 25000,
    })
    const output = `${result.stdout}${result.stderr}`.trim()
    return { ok: result.code === 0, output, config: file }
  }

  /**
   * Ask the running proxy to load the current file.
   * @returns {Promise<{ok: boolean, output: string}>} the reload result.
   */
  async reload() {
    const result = await run(
      this.exe(),
      ['reload', '--config', this.configPath, '--adapter', 'caddyfile'],
      { timeout: 25000 },
    )
    const output = `${result.stdout}${result.stderr}`.trim()
    return { ok: result.code === 0, output }
  }

  /**
   * Read the proxy's live admin state.
   * @param {number} [timeout] - request timeout in milliseconds.
   * @returns {Promise<{reachable: boolean, admin: string, listens: string[], error?: string}>} live state.
   */
  async status(timeout = 1500) {
    const admin = String(this.store.settings.adminEndpoint ?? 'localhost:2019').trim()
    const base = admin.startsWith('http') ? admin : `http://${admin}`
    const candidates = [base]
    // A Caddy started with `admin localhost:2019` answers only that Host name
    // and rejects 127.0.0.1 with 403, so probe the sibling spelling too.
    const alt = base.replace('//127.0.0.1', '//localhost').replace('//localhost', '//127.0.0.1')
    if (alt !== base) candidates.push(alt)
    let lastError
    for (const candidate of candidates) {
      try {
        const servers = await fetchJson(`${candidate}/config/apps/http/servers`, timeout)
        const listens = []
        for (const server of Object.values(servers ?? {})) {
          for (const listen of server?.listen ?? []) listens.push(String(listen))
        }
        return { reachable: true, admin, listens }
      } catch (error) {
        if (error && error.status === 403) {
          // The admin endpoint answered; it just refuses this Host spelling.
          return { reachable: true, admin, listens: [], restricted: true }
        }
        lastError = error
      }
    }
    return { reachable: false, admin, listens: [], error: String(lastError?.message ?? lastError) }
  }

  /**
   * Start the proxy as a child process of this plugin.
   * @returns {Promise<{ok: boolean, output: string}>} the start result.
   */
  async start() {
    if ((await this.status(800)).reachable) {
      return { ok: true, output: 'Caddy is already running' }
    }
    // Refuse to fight another instance for the admin or proxy port; a second
    // caddy exits immediately and that used to take the host down with it.
    if (await isPortListening(this.adminPort())) {
      return { ok: false, output: `admin port ${this.adminPort()} is already in use — another Caddy or program owns it` }
    }
    if (await isPortListening(this.proxyPort())) {
      return { ok: false, output: `proxy port ${this.proxyPort()} is already in use — start the listener yourself or free the port` }
    }
    const logFile = path.join(this.store.dirs.logs, 'caddy.log')
    await ensureDir(this.store.dirs.logs)
    const child = spawnCaptured(this.exe(), ['run', '--config', this.configPath, '--adapter', 'caddyfile'])
    this.child = child
    const { createWriteStream } = await import('node:fs')
    const stream = createWriteStream(logFile, { flags: 'a' })
    this.childLog = stream
    attachProcessLog(child, stream).write(`\n=== ${nowIso()} caddy run ===\n`)
    child.on('exit', () => {
      this.child = undefined
    })
    const deadline = Date.now() + 8000
    while (Date.now() < deadline) {
      await delay(250)
      if ((await this.status(600)).reachable) return { ok: true, output: 'Caddy started' }
      if (child.exitCode !== null) break
    }
    return { ok: false, output: 'Caddy did not become ready; see logs/caddy.log' }
  }

  /**
   * Port of the Caddy admin endpoint.
   * @returns {number} the TCP port.
   */
  adminPort() {
    const endpoint = String(this.store.settings.adminEndpoint ?? '127.0.0.1:2019')
    return Number(endpoint.slice(endpoint.lastIndexOf(':') + 1)) || 2019
  }

  /**
   * Port of the reverse proxy listener.
   * @returns {number} the TCP port.
   */
  proxyPort() {
    const listen = String(this.store.settings.proxyListen ?? ':8080')
    return Number(listen.slice(listen.lastIndexOf(':') + 1)) || 8080
  }

  /**
   * Stop the proxy through its admin API, then by port if that fails.
   * @returns {Promise<{ok: boolean, output: string}>} the stop result.
   */
  async stop() {
    const result = await run(this.exe(), ['stop'], { timeout: 10000 })
    if (result.code === 0) return { ok: true, output: 'Caddy stopped' }
    const { pidOnPort, killTree } = await import('./util.js')
    const listen = String(this.store.settings.proxyListen ?? ':8080')
    const port = Number(listen.slice(listen.lastIndexOf(':') + 1))
    const pid = await pidOnPort(port)
    if (!pid) return { ok: false, output: `${result.stdout}${result.stderr}`.trim() || 'Caddy is not running' }
    const killed = await killTree(pid)
    return { ok: killed.ok, output: killed.output }
  }

  /**
   * Render, validate, and reload in one transaction. A validation failure puts
   * the previous files back so the running proxy is never left half-configured.
   * @returns {Promise<{ok: boolean, output: string, rendered?: any}>} the outcome.
   */
  async apply() {
    const previous = {
      main: await readFileSafe(this.configPath),
      routes: await readFileSafe(this.managedRoutePath),
    }
    const rendered = await this.render()
    const validation = await this.validate()
    if (!validation.ok) {
      if (previous.main !== undefined) await writeFileAtomic(this.configPath, previous.main)
      if (previous.routes !== undefined) await writeFileAtomic(this.managedRoutePath, previous.routes)
      return { ok: false, output: validation.output || 'Caddyfile validation failed' }
    }
    const status = await this.status(800)
    if (!status.reachable) {
      return { ok: true, output: 'Configuration is valid; Caddy is not running so nothing was reloaded.', rendered }
    }
    const reload = await this.reload()
    return { ok: reload.ok, output: reload.output, rendered }
  }

  /**
   * Hash a plaintext password with Caddy's own bcrypt helper.
   * @param {string} plaintext - password.
   * @returns {Promise<string>} a `$2a$…` hash.
   */
  async hashPassword(plaintext) {
    if (typeof plaintext !== 'string' || plaintext.length === 0) {
      throw new Error('password is required')
    }
    const result = await run(this.exe(), ['hash-password', '--plaintext', plaintext], { timeout: 20000 })
    const hash = result.stdout.trim().split(/\r?\n/).pop() ?? ''
    if (result.code !== 0 || !hash.startsWith('$2')) {
      throw new Error(`caddy hash-password failed: ${`${result.stdout}${result.stderr}`.trim()}`)
    }
    return hash
  }

  /**
   * Read the current Caddyfile.
   * @returns {Promise<{path: string, content: string, mode: string}>} the file and its mode.
   */
  async readConfig() {
    const content = await readFileSafe(this.configPath)
    return { path: this.configPath, content: content ?? '', mode: this.store.state.caddy.mode }
  }

  /**
   * Replace the Caddyfile and switch to manual mode.
   * @param {string} content - new file body.
   * @returns {Promise<{ok: boolean, output: string}>} the validation result.
   */
  async writeConfig(content) {
    if (typeof content !== 'string') throw new Error('content must be a string')
    const backup = `${this.configPath}.${Date.now()}.bak`
    const previous = await readFileSafe(this.configPath)
    if (previous !== undefined) await writeFileAtomic(backup, previous)
    await writeFileAtomic(this.configPath, content)
    await this.store.setCaddyMode('manual')
    const validation = await this.validate()
    if (!validation.ok) return { ok: false, output: validation.output }
    const status = await this.status(800)
    if (!status.reachable) return { ok: true, output: 'Saved; Caddy is not running.' }
    const reload = await this.reload()
    return { ok: reload.ok, output: reload.output }
  }

  /** Stop the child process this plugin owns, if any. */
  async dispose() {
    try {
      if (this.child && this.child.exitCode === null) this.child.kill()
    } catch {
      /* already gone */
    }
    try {
      this.childLog?.end()
    } catch {
      /* already ended */
    }
  }
}

/**
 * Fetch JSON with a hard timeout.
 * @param {string} url - request URL.
 * @param {number} timeout - milliseconds.
 * @returns {Promise<any>} parsed body.
 */
async function fetchJson(url, timeout) {
  const response = await fetch(url, { signal: AbortSignal.timeout(Math.max(100, timeout)) })
  if (!response.ok) {
    const error = new Error(`HTTP ${response.status}`)
    error.status = response.status
    throw error
  }
  return response.json()
}

/**
 * Read a file, returning undefined when it does not exist.
 * @param {string} file - absolute path.
 * @returns {Promise<string | undefined>} contents.
 */
async function readFileSafe(file) {
  try {
    return await readFile(file, 'utf8')
  } catch (error) {
    if (error && error.code === 'ENOENT') return undefined
    throw error
  }
}

/**
 * Sleep for a fixed time.
 * @param {number} ms - milliseconds.
 * @returns {Promise<void>} resolves after the delay.
 */
function delay(ms) {
  return new Promise(resolve => setTimeout(resolve, ms))
}
